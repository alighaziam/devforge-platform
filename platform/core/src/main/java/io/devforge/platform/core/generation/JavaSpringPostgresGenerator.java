    @Override
    public boolean supports(JsonNode spec) {
        if (spec == null || !DESCRIPTOR.supportedSpecificationVersions()
                .contains(spec.path("specVersion").asText())) {
            return false;
        }
        try {
            validateStack(spec);
            validateIndexes(spec.path("model"));
            return true;
        } catch (ResponseStatusException exception) {
            return false;
        }
    }

