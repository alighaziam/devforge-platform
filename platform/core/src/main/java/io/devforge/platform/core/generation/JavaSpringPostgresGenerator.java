    private void validateStack(JsonNode spec) {
        Map<String, String> selected = new HashMap<>();
        spec.path("technologySelections").fields().forEachRemaining(entry -> {
            String id = entry.getValue().path("id").asText();
            if (!id.isBlank()) selected.put(id, entry.getValue().path("version").asText());
        });
        DESCRIPTOR.supportedTechnologyVersions().forEach((technologyId, version) ->
                require(selected, technologyId, version));
        if (selected.size() != DESCRIPTOR.supportedTechnologyVersions().size()) {
            String supported = DESCRIPTOR.supportedTechnologyVersions().entrySet().stream()
                    .map(entry -> entry.getKey() + " " + entry.getValue())
                    .collect(java.util.stream.Collectors.joining(", "));
            throw rejected("Generator " + VERSION + " supports only: " + supported + ".");
        }
        if (!Set.of("layered", "modular-monolith").contains(spec.path("architecture").path("style").asText()))
            throw rejected("Unsupported architecture style for generator 0.1.0.");
        if (!"single-project".equals(spec.path("generation").path("outputLayout").asText()))
            throw rejected("Generator 0.1.0 supports single-project output only.");
        String auth = spec.path("security").path("authentication").asText("none");
        if (!"none".equals(auth)) throw rejected("Identity integration is not yet supported by generator 0.1.0.");
    }

    private void validateIndexes(JsonNode model) {
        Map<String, Set<String>> columnsByTable = new HashMap<>();
        for (JsonNode entity : model.path("entities")) {
            String table = snake(entity.path("name").asText());
            Set<String> columns = new HashSet<>();
            boolean hasId = false;
            for (JsonNode attribute : entity.path("attributes")) {
                String column = snake(attribute.path("name").asText());
                if (!columns.add(column)) throw rejected("Duplicate SQL column name: " + table + "." + column);
                hasId |= "id".equals(fieldName(attribute.path("name").asText()));
            }
            if (!hasId) columns.add("id");
            if (columnsByTable.putIfAbsent(table, columns) != null) {
                throw rejected("Duplicate SQL table name: " + table);
            }
        }
        List<ForeignKey> relationships = foreignKeys(model);
        Set<String> indexNames = new HashSet<>();
        for (ForeignKey relationship : relationships) {
            Set<String> columns = columnsByTable.get(snake(relationship.ownerEntity()));
            if (columns != null) columns.add(relationship.column());
            if (!relationship.unique() && !indexNames.add(relationship.indexName())) {
                throw rejected("Duplicate index name: " + relationship.indexName());
            }
        }

        for (JsonNode index : model.path("indexes")) {
            String table = snake(index.path("entity").asText());
            Set<String> columns = columnsByTable.get(table);
            if (columns == null) throw rejected("Index references an unknown entity: " + table);
            List<String> indexedColumns = new ArrayList<>();
            index.path("columns").forEach(value -> indexedColumns.add(snake(value.asText())));
            if (indexedColumns.isEmpty()) throw rejected("Index must include at least one column.");
            for (String column : indexedColumns) {
                if (!columns.contains(column)) {
                    throw rejected("Index references an unknown column: " + table + "." + column);
                }
            }
            String method = index.path("method").asText("btree").toLowerCase(Locale.ROOT);
            if (!"btree".equals(method)) {
                throw rejected("Generator 0.1.0 supports PostgreSQL btree indexes only.");
            }
            String name = index.hasNonNull("name") ? snake(index.path("name").asText())
                    : "idx_" + table + "_" + String.join("_", indexedColumns);
            if (!indexNames.add(name)) throw rejected("Duplicate index name: " + name);
        }
    }

    private void require(Map<String, String> values, String id, String version) {
        if (!version.equals(values.get(id))) throw rejected("Required technology selection: " + id + "@" + version);
    }

    private String controllerSource(JsonNode entity, String cls, String pkg,
                                    List<ForeignKey> relationships) {
        String route = snake(entity.path("name").asText());
        StringBuilder out = new StringBuilder();
        out.append("package ").append(pkg).append(".controller;\n")
                .append("import ").append(pkg).append(".model.").append(cls).append(";\n")
                .append("import ").append(pkg).append(".repository.").append(cls).append("Repository;\n")
                .append("import org.springframework.http.ResponseEntity;\n")
                .append("import org.springframework.web.bind.annotation.*;\n")
                .append("import java.net.URI;\nimport java.util.List;\nimport java.util.UUID;\n")
                .append("@RestController @RequestMapping(\"/api/").append(route).append("\")\n")
                .append("public class ").append(cls).append("Controller {\n")
                .append("  private final ").append(cls).append("Repository repository;\n")
                .append("  public ").append(cls).append("Controller(").append(cls)
                .append("Repository repository) { this.repository = repository; }\n")
                .append("  @GetMapping public List<").append(cls).append("> list() { return repository.findAll(); }\n")
                .append("  @GetMapping(\"/{id}\") public ResponseEntity<").append(cls)
                .append("> get(@PathVariable UUID id) {\n")
                .append("    return repository.findById(id).map(ResponseEntity::ok).orElseGet(() -> ResponseEntity.notFound().build());\n")
                .append("  }\n")
                .append("  @PostMapping public ResponseEntity<").append(cls).append("> create(@RequestBody ")
                .append(cls).append(" value) {\n")
                .append("    ").append(cls).append(" saved = repository.save(value);\n")
                .append("    return ResponseEntity.created(URI.create(\"/api/").append(route)
                .append("/\" + saved.getId())).body(saved);\n")
                .append("  }\n")
                .append("  @PutMapping(\"/{id}\") public ResponseEntity<").append(cls)
                .append("> update(@PathVariable UUID id, @RequestBody ").append(cls).append(" value) {\n")
                .append("    return repository.findById(id).map(existing -> {\n");
        for (JsonNode attribute : entity.path("attributes")) {
            String field = fieldName(attribute.path("name").asText());
            if ("id".equals(field)) continue;
            String capitalized = Character.toUpperCase(field.charAt(0)) + field.substring(1);
            out.append("      existing.set").append(capitalized).append("(value.get")
                    .append(capitalized).append("());\n");
        }
        for (ForeignKey relationship : relationships) {
            if (!relationship.ownerEntity().equals(entity.path("name").asText())) continue;
            String capitalized = Character.toUpperCase(relationship.field().charAt(0))
                    + relationship.field().substring(1);
            out.append("      existing.set").append(capitalized).append("(value.get")
                    .append(capitalized).append("());\n");
        }
        out.append("      return ResponseEntity.ok(repository.save(existing));\n")
                .append("    }).orElseGet(() -> ResponseEntity.notFound().build());\n")
                .append("  }\n")
                .append("  @DeleteMapping(\"/{id}\") public ResponseEntity<Void> delete(@PathVariable UUID id) {\n")
                .append("    if (!repository.existsById(id)) return ResponseEntity.notFound().build();\n")
                .append("    repository.deleteById(id); return ResponseEntity.noContent().build();\n")
                .append("  }\n")
                .append("}\n");
        return out.toString();
    }

    private String entitySource(JsonNode entity, String cls, String pkg, List<ForeignKey> relationships) {
        StringBuilder out = new StringBuilder("package ").append(pkg).append(".model;\n")
                .append("import jakarta.persistence.*;\nimport java.math.BigDecimal;\n")
                .append("import java.time.Instant;\nimport java.time.LocalDate;\nimport java.util.UUID;\n")
                .append("@Entity @Table(name = \"\\\"").append(snake(entity.path("name").asText()))
                .append("\\\"\") public class ").append(cls).append(" {\n");
        boolean id = false;
        Set<String> fields = new HashSet<>();
        for (JsonNode a : entity.path("attributes")) {
            String original = a.path("name").asText();
            String field = fieldName(original);
            if (!fields.add(field)) throw rejected("Duplicate field name: " + field);
            String type = a.path("type").asText().toLowerCase(Locale.ROOT);
            if (a.hasNonNull("default")) throw rejected("Attribute defaults are not supported: " + original);
            if ("id".equals(field)) {
                if (!"uuid".equals(type)) throw rejected("An explicit id field must use uuid.");
                id = true;
                out.append("@Id ");
            }
            out.append("@Column(name = \"\\\"").append(snake(original)).append("\\\"\", nullable = ")
                    .append(!a.path("required").asBoolean(false));
            if (a.path("unique").asBoolean(false)) out.append(", unique = true");
            if ("string".equals(type)) out.append(", length = 255");
            if ("text".equals(type)) out.append(", columnDefinition = \"text\"");
            if ("decimal".equals(type)) out.append(", precision = 19, scale = 4");
            out.append(") private ").append(javaType(type)).append(' ').append(field).append(";\n");
        }
        if (!id) out.append("@Id @GeneratedValue(strategy = GenerationType.UUID) private UUID id;\n");
        for (ForeignKey relationship : relationships) {
            if (!relationship.ownerEntity().equals(entity.path("name").asText())) continue;
            String mapping = relationship.unique() ? "OneToOne" : "ManyToOne";
            out.append('@').append(mapping).append("(fetch = FetchType.LAZY) @JoinColumn(name = \"\\\"")
                    .append(relationship.column()).append("\\\"\", nullable = ").append(!relationship.required());
            if (relationship.unique()) out.append(", unique = true");
            out.append(") private ").append(relationship.javaType()).append(' ')
                    .append(relationship.field()).append(";\n");
        }
        out.append("protected ").append(cls).append("() { }\n");
        for (JsonNode attribute : entity.path("attributes")) {
            String field = fieldName(attribute.path("name").asText());
            String type = javaType(attribute.path("type").asText().toLowerCase(Locale.ROOT));
            String capitalized = Character.toUpperCase(field.charAt(0)) + field.substring(1);
            out.append("public ").append(type).append(" get").append(capitalized)
                    .append("() { return ").append(field).append("; }\n")
                    .append("public void set").append(capitalized).append("(").append(type)
                    .append(" value) { this.").append(field).append(" = value; }\n");
        }
        if (!id) out.append("public UUID getId() { return id; }\n");
        for (ForeignKey relationship : relationships) {
            if (!relationship.ownerEntity().equals(entity.path("name").asText())) continue;
            String capitalized = Character.toUpperCase(relationship.field().charAt(0)) + relationship.field().substring(1);
            out.append("public ").append(relationship.javaType()).append(" get").append(capitalized)
                    .append("() { return ").append(relationship.field()).append("; }\n")
                    .append("public void set").append(capitalized).append("(").append(relationship.javaType())
                    .append(" value) { this.").append(relationship.field()).append(" = value; }\n");
        }
        return out.append("}\n").toString();
    }

    private String migration(JsonNode model) {
        List<ForeignKey> relationships = foreignKeys(model);
        StringBuilder sql = new StringBuilder("-- Generated by DevForge; review before production use.\n");
        for (JsonNode entity : model.path("entities")) {
            List<String> columns = new ArrayList<>();
            boolean id = false;
            for (JsonNode a : entity.path("attributes")) {
                String name = snake(a.path("name").asText());
                String field = fieldName(a.path("name").asText());
                String type = a.path("type").asText().toLowerCase(Locale.ROOT);
                id |= "id".equals(field);
                String col = "    \"" + name + "\" " + sqlType(type);
                if (a.path("required").asBoolean(false)) col += " NOT NULL";
                if (a.path("unique").asBoolean(false)) col += " UNIQUE";
                if ("id".equals(field)) col += " PRIMARY KEY";
                columns.add(col);
            }
            if (!id) columns.add(0, "    \"id\" UUID PRIMARY KEY");
            for (ForeignKey relationship : relationships) {
                if (!relationship.ownerEntity().equals(entity.path("name").asText())) continue;
                String column = "    \"" + relationship.column() + "\" UUID";
                if (relationship.required()) column += " NOT NULL";
                if (relationship.unique()) column += " UNIQUE";
                columns.add(column);
            }
            sql.append("\nCREATE TABLE \"").append(snake(entity.path("name").asText())).append("\"")
                    .append(" (\n").append(String.join(",\n", columns)).append("\n);\n");
        }
        for (JsonNode idx : model.path("indexes")) {
            String table = snake(idx.path("entity").asText());
            List<String> cols = new ArrayList<>();
            List<String> indexColumns = new ArrayList<>();
            idx.path("columns").forEach(v -> {
                String column = snake(v.asText());
                indexColumns.add(column);
                cols.add("\"" + column + "\"");
            });
            if (cols.isEmpty()) throw rejected("Index must include at least one column.");
            String name = idx.hasNonNull("name") ? snake(idx.path("name").asText())
                    : "idx_" + table + "_" + String.join("_", indexColumns);
            if (name.length() > 63) throw rejected("Generated index name exceeds PostgreSQL's 63-character limit.");
            sql.append("\nCREATE ");
            if (idx.path("unique").asBoolean(false)) sql.append("UNIQUE ");
            sql.append("INDEX \"").append(name).append("\" ON \"").append(table).append("\"")
                    .append(" (").append(String.join(", ", cols)).append(");\n");
        }
        for (ForeignKey relationship : relationships) {
            sql.append("\nALTER TABLE \"").append(snake(relationship.ownerEntity()))
                    .append("\" ADD CONSTRAINT \"").append(relationship.constraintName())
                    .append("\" FOREIGN KEY (\"").append(relationship.column())
                    .append("\") REFERENCES \"").append(snake(relationship.targetEntity()))
                    .append("\" (\"id\");\n");
            if (!relationship.unique()) {
                sql.append("\nCREATE INDEX \"").append(relationship.indexName())
                        .append("\" ON \"").append(snake(relationship.ownerEntity()))
                        .append("\" (\"").append(relationship.column()).append("\");\n");
            }
        }
        return sql.toString();
    }

    private String javaMigration(JsonNode model) {
        String sql = migration(model).replaceFirst("(?m)^--[^\r\n]*\r?\n", "");
        List<String> statements = Arrays.stream(sql.split(";"))
                .map(String::trim)
                .filter(statement -> !statement.isEmpty())
                .toList();
        StringBuilder source = new StringBuilder("package db.migration;\n\n")
                .append("import org.flywaydb.core.api.migration.BaseJavaMigration;\n")
                .append("import org.flywaydb.core.api.migration.Context;\n")
                .append("import java.sql.Statement;\n\n")
                .append("public class V1__CreateDomainSchema extends BaseJavaMigration {\n")
                .append("  private static final String[] STATEMENTS = {\n");
        for (String statement : statements) {
            source.append("    \"").append(escapeJava(statement)).append("\",\n");
        }
        source.append("  };\n")
                .append("  @Override public void migrate(Context context) throws Exception {\n")
                .append("    try (Statement statement = context.getConnection().createStatement()) {\n")
                .append("      for (String sql : STATEMENTS) statement.execute(sql);\n")
                .append("    }\n")
                .append("  }\n")
                .append("}\n");
        return source.toString();
    }

    private String escapeJava(String value) {
        return value.replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\r", "\\r")
                .replace("\n", "\\n")
                .replace("\t", "\\t");
    }

    private String javaType(String type) {
        return switch (type) {
            case "string", "text" -> "String";
            case "integer" -> "Integer";
            case "long" -> "Long";
            case "decimal" -> "BigDecimal";
            case "boolean" -> "Boolean";
            case "uuid" -> "UUID";
            case "date" -> "LocalDate";
            case "datetime" -> "Instant";
            default -> throw rejected("Unsupported model attribute type: " + type);
        };
    }

    private String sqlType(String type) {
        return switch (type) {
            case "string" -> "VARCHAR(255)";
            case "text" -> "TEXT";
            case "integer" -> "INTEGER";
            case "long" -> "BIGINT";
            case "decimal" -> "NUMERIC(19,4)";
            case "boolean" -> "BOOLEAN";
            case "uuid" -> "UUID";
            case "date" -> "DATE";
            case "datetime" -> "TIMESTAMP WITH TIME ZONE";
            default -> throw rejected("Unsupported model attribute type: " + type);
        };
    }

